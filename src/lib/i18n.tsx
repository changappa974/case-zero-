const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    try {
      const saved = localStorage.getItem('cz_language');
      return saved === 'kn' ? 'kn' : 'en';
    } catch (e) {
      return 'en';
    }
  });

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    try {
      localStorage.setItem('cz_language', lang);
    } catch (e) {}
  };

  const toggleLanguage = () => {
    setLanguage(language === 'en' ? 'kn' : 'en');
  };

  const t = (key: string, fallback?: string): string => {
    if (language === 'kn') {
      return KANNADA_TRANSLATIONS[key] || fallback || key;
    }
    return fallback || key;
  };

  const getTranslatedCase = (): MysteryCase => {
    if (language === 'en') return CASE_DATA;
    return {
      ...CASE_DATA,
      title: 'ಕೇಸ್ ಝೀರೋ: ಫ್ರಾಸ್ಟ್‌ಪೀಕ್ ಕನ್ಸರ್ವೇಟರಿಯಲ್ಲಿ ಕೊಲೆ',
      tagline: '“ಪ್ರತಿಯೊಂದು ವಿವರವೂ ಒಂದು ಕಥೆ ಹೇಳುತ್ತದೆ. ಸತ್ಯವನ್ನು ಹುಡುಕಬಲ್ಲಿರಾ?”',
      description: 'ಫ್ರಾಸ್ಟ್‌ಪೀಕ್ ಕನ್ಸರ್ವೇಟರಿಯ ಗಾಜಿನ ಸಭಾಂಗಣದಲ್ಲಿ ಮುಖ್ಯ ಸಸ್ಯಶಾಸ್ತ್ರಜ್ಞ ಡಾ. ಆರ್ಥರ್ ವ್ಯಾನ್ಸ್ ನೆಲದ ಮೇಲೆ ಶವವಾಗಿ ಪತ್ತೆಯಾಗಿದ್ದಾರೆ. ದೇಹದ ಪಕ್ಕದಲ್ಲಿ ಚಹಾ ಕಪ್, ಒಡೆದ ಕನ್ನಡಕ, ನಿಂತ ಗಡಿಯಾರ ಮತ್ತು ನೀಲಿ ಬಣ್ಣದ ಹೊಳೆಯುವ ಆರ್ಕಿಡ್ ಪರಾಗದ ಜಾರ್ ಬಿದ್ದಿದೆ. ರಾತ್ರಿ ೧೦:೫೦ ಮತ್ತು ೧೧:೩೦ ರ ನಡುವೆ ನಾಲ್ಕು ವ್ಯಕ್ತಿಗಳು ಉಪಸ್ಥಿತರಿದ್ದರು. ಸಿಸಿಟಿವಿ ದೃಶ್ಯಗಳನ್ನು ಪರಿಶೀಲಿಸಿ, ಪುರಾವೆಗಳನ್ನು ಸಂಯೋಜಿಸಿ ಕೊಲೆಗಾರನನ್ನು ಪತ್ತೆಹಚ್ಚಿ.',
      location: 'ಫ್ರಾಸ್ಟ್‌ಪೀಕ್ ಕನ್ಸರ್ವೇಟರಿ ಮತ್ತು ಬಿ-ವಿಂಗ್ ಪ್ರಯೋಗಾಲಯ',
    };
  };

  const getTranslatedSuspects = (): Suspect[] => {
    if (language === 'en') return INITIAL_SUSPECTS;
    return INITIAL_SUSPECTS.map((s) => {
      const kn = KANNADA_SUSPECTS[s.id];
      if (!kn) return s;
      return {
        ...s,
        display_name: kn.display_name || s.display_name,
        role: kn.role || s.role,
        public_profile: {
          ...s.public_profile,
          ...(kn.public_profile || {})
        }
      };
    });
  };

  const getTranslatedEvidence = (): Evidence[] => {
    if (language === 'en') return INITIAL_EVIDENCE;
    return INITIAL_EVIDENCE.map((e) => {
      const kn = KANNADA_EVIDENCE[e.code];
      if (!kn) return e;
      return {
        ...e,
        title: kn.title || e.title,
        description: kn.description || e.description,
      };
    });
  };

  const getTranslatedCCTV = (): CCTVFeed[] => {
    if (language === 'en') return CCTV_FEEDS;
    return CCTV_FEEDS.map((feed) => {
      const kn = KANNADA_CCTV[feed.id];
      if (!kn) return feed;
      return {
        ...feed,
        title: kn.title || feed.title,
        location: kn.location || feed.location,
      };
    });
  };

  const getTranslatedAudioLogs = (): AudioLog[] => {
    if (language === 'en') return AUDIO_LOGS;
    return AUDIO_LOGS.map((log) => {
      return {
        ...log,
        title: log.id === 'aud-1' ? 'ಚಹಾ ತಲುಪಿಸುವಿಕೆ (೧೧:೦೦ PM)' :
               log.id === 'aud-2' ? 'ಹೀಟರ್ ತಪಾಸಣೆ (೧೧:೦೬ PM)' :
               log.id === 'aud-3' ? 'ರಹಸ್ಯ ಬಾಗಿಲಿನ ಸದ್ದು (೧೧:೧೪ PM)' : 'ವಿಷದ ಪರಿಣಾಮ & ಸಾವು (೧೧:೨೪ PM)',
      };
    });
  };

  return (
    <LanguageContext.Provider
      value={{
        language,
        setLanguage,
        toggleLanguage,
        t,
        isKannada: language === 'kn',
        getTranslatedCase,
        getTranslatedSuspects,
        getTranslatedEvidence,
        getTranslatedCCTV,
        getTranslatedAudioLogs,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = (): LanguageContextType => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};
